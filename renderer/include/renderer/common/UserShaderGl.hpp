#pragma once

#include <string>
#include <vector>

// The OpenGL half of the user shaders (orchestrator/proposals/user-shaders.md, stage 4) that needs no GL context, so the CI
// (where GL cannot run) can test it as text: the engine's vertex stage as GLSL 330 text, and every uniform NAME the renderer sets by
// name on a user program. OpenGLRenderer takes the vertex source and all the names from here, and the tests compare them with the
// cooked fragment text (the prelude of renderer/shaders/user/prelude/opengl.glsl) of every fixture, so a name the renderer sets
// that the prelude does not declare, or the other way round, fails a test on any machine.
namespace Renderer::Common::UserGl
{
    /// The engine's vertex stage for every user shader (GLSL 330 core): the Common::Vertex attributes at locations 0-4 (as the
    /// built-in shaders), the per-draw uniforms under the contract's n2_ names, and the five varyings the prelude declares as
    /// fragment inputs (n2_UV, n2_Color, n2_WorldPos, n2_Normal, n2_Tangent, matched by name). OpenGL's clip space is the one the
    /// engine's projection gives, so there is no z remap (Vulkan and WebGPU remap)
    [[nodiscard]] const char* VertexSource();

    /// The per-draw uniforms the renderer sets by name on every user program (the contract's PerDraw members and
    /// n2_TargetHeight, the OpenGL prelude's extra). A program that does not use one has location -1 and is skipped
    inline constexpr const char* kModel = "n2_Model";
    inline constexpr const char* kView = "n2_View";
    inline constexpr const char* kProjection = "n2_Projection";
    inline constexpr const char* kStageDim = "n2_StageDim";
    inline constexpr const char* kTintSaturation = "n2_TintSaturation";
    inline constexpr const char* kTintInside = "n2_TintInside";
    inline constexpr const char* kTintCircle = "n2_TintCircle";
    inline constexpr const char* kTargetHeight = "n2_TargetHeight";
    [[nodiscard]] std::vector<std::string> PerDrawUniformNames();

    /// The sampler uniform of texture slot `slot` (0-4); the renderer binds it to texture unit `slot`
    [[nodiscard]] std::string TextureSamplerName(unsigned slot);

    /// The names of the scene-lighting uniforms of a program whose manifest says "uses": ["lighting"]. Spelled differently from
    /// the built-in lit shader's (uAmbientLight ...): the contract's n2_ names, with the OpenGL prelude's n2_EncodeOutputFlag for
    /// the flag the Vulkan and WebGPU blocks call n2_EncodeOutput (a GLSL function of that name exists)
    struct LightingNames
    {
        const char* encodeOutput;
        const char* ambient;
        const char* cameraPos;
        const char* numDirectional;
        const char* numPoint;
        const char* numSpot;
        const char* directionalArray;
        const char* pointArray;
        const char* spotArray;
    };
    inline constexpr LightingNames kUserLightingNames{"n2_EncodeOutputFlag", "n2_AmbientLight",    "n2_CameraPos",
                                                       "n2_NumDirectionalLights", "n2_NumPointLights", "n2_NumSpotLights",
                                                       "n2_DirectionalLights",    "n2_PointLights",    "n2_SpotLights"};

    /// "array[index].member", the name of one member of one element of a light array
    [[nodiscard]] std::string LightMember(const char* array, int index, const char* member);

    /// Every lighting uniform name a user program may have, for all the light slots (the arrays' sizes are
    /// SceneLightingData::MAX_*): what the tests look for in the prelude
    [[nodiscard]] std::vector<std::string> LightingUniformNames();

    /// The reason the cooked fragment text of a user shader is not acceptable to hand to a driver, or an empty string: it must be
    /// the generated `#version 330 core` text (that line first, no other #version, no #extension line at all, no NUL byte), at
    /// most kUserShaderMaxGlslBytes, with a `void main` and not an `#include`-style escape. The text is generated by tools/n2shader
    /// from the header and the author's stage, but a pack or mod may carry any bytes
    [[nodiscard]] std::string ValidateFragmentSource(const std::string& text);
}
