/* Docs search: a search box in the top right of every page. No dependencies, no server.
   The index (assets/search-index.js, generated by docs/tools/build-search-index.mjs) is loaded the first
   time the box is used. Keys: "/" or Ctrl/Cmd+K focus the box, arrows move through the results, Enter
   opens one, Escape closes. Pages work without this script. */
(function () {
  "use strict";

  var MAX_RESULTS = 20;
  var SNIPPET_BEFORE = 50;
  var SNIPPET_LENGTH = 170;

  var main = document.getElementById("main");
  if (!main || document.querySelector(".docsearch")) return;

  // Where this script lives, so the index loads from the same folder on any page or host.
  var scriptEl = document.currentScript || document.querySelector('script[src$="assets/search.js"]');
  var base = scriptEl ? scriptEl.src.replace(/search\.js(?:[?#].*)?$/, "") : "assets/";

  var bar = document.createElement("div");
  bar.className = "docsearch-bar";
  bar.innerHTML =
    '<div class="docsearch" role="search">' +
    '<button type="button" class="docsearch-toggle" aria-label="Search the docs" aria-expanded="false" aria-controls="docsearch-panel">' +
    '<svg viewBox="0 0 24 24" width="20" height="20" aria-hidden="true" focusable="false"><circle cx="10.5" cy="10.5" r="6.5" fill="none" stroke="currentColor" stroke-width="2"/><path d="M15.5 15.5 21 21" stroke="currentColor" stroke-width="2" stroke-linecap="round"/></svg>' +
    "</button>" +
    '<div class="docsearch-panel" id="docsearch-panel">' +
    '<label class="docsearch-label" for="docsearch-input">Search the docs</label>' +
    '<div class="docsearch-field">' +
    '<svg class="docsearch-icon" viewBox="0 0 24 24" width="16" height="16" aria-hidden="true" focusable="false"><circle cx="10.5" cy="10.5" r="6.5" fill="none" stroke="currentColor" stroke-width="2"/><path d="M15.5 15.5 21 21" stroke="currentColor" stroke-width="2" stroke-linecap="round"/></svg>' +
    '<input id="docsearch-input" class="docsearch-input" type="search" placeholder="Search the docs" autocomplete="off" spellcheck="false" ' +
    'role="combobox" aria-autocomplete="list" aria-expanded="false" aria-controls="docsearch-results" aria-describedby="docsearch-hint">' +
    '<kbd class="docsearch-kbd" aria-hidden="true">/</kbd>' +
    '<button type="button" class="docsearch-close" aria-label="Close search">' +
    '<svg viewBox="0 0 24 24" width="18" height="18" aria-hidden="true" focusable="false"><path d="M6 6l12 12M18 6 6 18" stroke="currentColor" stroke-width="2" stroke-linecap="round"/></svg>' +
    "</button>" +
    "</div>" +
    '<span id="docsearch-hint" class="docsearch-label">Press slash or Control K to search. Use the arrow keys to move through the results and Enter to open one.</span>' +
    '<ul id="docsearch-results" class="docsearch-results" role="listbox" aria-label="Search results" hidden></ul>' +
    '<p class="docsearch-status" role="status" aria-live="polite"></p>' +
    "</div>" +
    "</div>";
  main.insertBefore(bar, main.firstChild);

  var root = bar.firstChild;
  var toggle = root.querySelector(".docsearch-toggle");
  var input = root.querySelector(".docsearch-input");
  var closeBtn = root.querySelector(".docsearch-close");
  var list = root.querySelector(".docsearch-results");
  var status = root.querySelector(".docsearch-status");

  var index = null;      // { pages, sections } once loaded
  var loading = false;
  var loadFailed = false;
  var results = [];
  var active = -1;
  var timer = 0;

  /* ---------- Index loading ---------- */

  function loadIndex() {
    if (index || loading) return;
    if (window.N2DocsSearchIndex) { prepare(window.N2DocsSearchIndex); return; }
    loading = true;
    var s = document.createElement("script");
    s.src = base + "search-index.js";
    s.async = true;
    s.onload = function () {
      loading = false;
      if (window.N2DocsSearchIndex) prepare(window.N2DocsSearchIndex);
      else fail();
    };
    s.onerror = function () { loading = false; fail(); };
    document.head.appendChild(s);
  }

  function fail() {
    loadFailed = true;
    if (input.value.trim()) render();
  }

  function prepare(data) {
    var sections = data.sections;
    for (var i = 0; i < sections.length; i++) {
      var s = sections[i];
      s.page = data.pages[s.p];
      s.lh = s.h.toLowerCase();
      s.lt = s.page.t.toLowerCase();
      s.lx = s.x.toLowerCase();
    }
    index = data;
    if (input.value.trim()) render();
  }

  /* ---------- Matching ---------- */

  function terms(q) {
    var out = [];
    q.toLowerCase().split(/\s+/).forEach(function (t) {
      if (t && out.indexOf(t) < 0) out.push(t);
    });
    // Longest first, so highlighting prefers "transform" over "trans" where both are typed.
    return out.sort(function (a, b) { return b.length - a.length; });
  }

  function count(hay, needle) {
    var n = 0, i = hay.indexOf(needle);
    while (i >= 0 && n < 50) { n++; i = hay.indexOf(needle, i + needle.length); }
    return n;
  }

  function search(q) {
    var ts = terms(q);
    var phrase = q.trim().toLowerCase().replace(/\s+/g, " ");
    var found = [];
    if (!ts.length) return found;
    var sections = index.sections;
    for (var i = 0; i < sections.length; i++) {
      var s = sections[i];
      var score = 0, ok = true;
      for (var j = 0; j < ts.length; j++) {
        var t = ts[j];
        var inH = s.lh.indexOf(t) >= 0;
        var inT = s.lt.indexOf(t) >= 0;
        var nX = count(s.lx, t);
        if (!inH && !inT && !nX) { ok = false; break; }
        score += (inH ? 30 : 0) + (inT ? 12 : 0) + Math.min(nX, 10);
      }
      if (!ok) continue;
      if (ts.length > 1) {
        if (s.lh.indexOf(phrase) >= 0) score += 40;
        else if (s.lx.indexOf(phrase) >= 0) score += 15;
      }
      if (s.lh === phrase) score += 40;
      if (!s.a) score += 2; // a page's own top section
      found.push({ s: s, score: score });
    }
    found.sort(function (a, b) { return b.score - a.score || a.s.p - b.s.p; });
    return found.slice(0, MAX_RESULTS);
  }

  /* ---------- Rendering ---------- */

  function esc(s) {
    return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
  }

  // Escapes text and wraps every occurrence of the terms in <mark>.
  function highlight(text, ts) {
    var lower = text.toLowerCase();
    var marks = [];
    ts.forEach(function (t) {
      var i = lower.indexOf(t);
      while (i >= 0) {
        marks.push([i, i + t.length]);
        i = lower.indexOf(t, i + t.length);
      }
    });
    marks.sort(function (a, b) { return a[0] - b[0] || b[1] - a[1]; });
    var out = "", pos = 0;
    for (var k = 0; k < marks.length; k++) {
      var m = marks[k];
      if (m[0] < pos) continue; // overlaps a mark already placed
      out += esc(text.slice(pos, m[0])) + "<mark>" + esc(text.slice(m[0], m[1])) + "</mark>";
      pos = m[1];
    }
    return out + esc(text.slice(pos));
  }

  function snippet(s, ts) {
    var x = s.x;
    if (!x) return "";
    var at = -1;
    for (var j = 0; j < ts.length && at < 0; j++) at = s.lx.indexOf(ts[j]);
    var start = 0;
    if (at > SNIPPET_BEFORE) {
      start = at - SNIPPET_BEFORE;
      var sp = x.indexOf(" ", start);
      if (sp >= 0 && sp < at) start = sp + 1;
    }
    var end = Math.min(x.length, start + SNIPPET_LENGTH);
    if (end < x.length) {
      var sp2 = x.lastIndexOf(" ", end);
      if (sp2 > start + SNIPPET_LENGTH / 2) end = sp2;
    }
    return (start > 0 ? "…" : "") + highlight(x.slice(start, end), ts) + (end < x.length ? "…" : "");
  }

  function hrefOf(s) {
    return s.page.u + (s.a ? "#" + s.a : "");
  }

  function setStatus(text) {
    status.textContent = text;
  }

  function show(on) {
    list.hidden = !on;
    input.setAttribute("aria-expanded", on ? "true" : "false");
    root.classList.toggle("has-results", on);
  }

  function render() {
    var q = input.value.trim();
    active = -1;
    input.removeAttribute("aria-activedescendant");
    if (!q) { list.innerHTML = ""; results = []; show(false); setStatus(""); return; }
    if (!index) {
      list.innerHTML = '<li class="docsearch-empty" role="presentation">' +
        (loadFailed ? "The search index could not be loaded." : "Loading the search index…") + "</li>";
      results = [];
      show(true);
      setStatus(loadFailed ? "The search index could not be loaded." : "Loading the search index.");
      return;
    }
    var ts = terms(q);
    results = search(q);
    if (!results.length) {
      list.innerHTML = '<li class="docsearch-empty" role="presentation">No results for “' + esc(q) + "”</li>";
      show(true);
      setStatus("No results.");
      return;
    }
    var html = "";
    for (var i = 0; i < results.length; i++) {
      var s = results[i].s;
      var where = s.a ? '<span class="docsearch-sep" aria-hidden="true"> › </span><span class="docsearch-section">' + highlight(s.h, ts) + "</span>" : "";
      html += '<li role="option" id="docsearch-opt-' + i + '" aria-selected="false" class="docsearch-result">' +
        '<a href="' + esc(hrefOf(s)) + '" tabindex="-1">' +
        '<span class="docsearch-where"><span class="docsearch-page">' + highlight(s.page.t, ts) + "</span>" + where + "</span>" +
        '<span class="docsearch-snippet">' + snippet(s, ts) + "</span>" +
        "</a></li>";
    }
    list.innerHTML = html;
    show(true);
    setStatus(results.length + (results.length === 1 ? " result." : " results.") +
      (results.length === MAX_RESULTS ? " Showing the best " + MAX_RESULTS + "." : ""));
  }

  function setActive(i) {
    var opts = list.querySelectorAll('[role="option"]');
    if (!opts.length) return;
    if (active >= 0 && opts[active]) opts[active].setAttribute("aria-selected", "false");
    active = (i + opts.length) % opts.length;
    var el = opts[active];
    el.setAttribute("aria-selected", "true");
    input.setAttribute("aria-activedescendant", el.id);
    el.scrollIntoView({ block: "nearest" });
  }

  /* ---------- Opening and closing ---------- */

  function isOpenNarrow() { return root.classList.contains("is-open"); }

  function open() {
    root.classList.add("is-open");
    toggle.setAttribute("aria-expanded", "true");
    loadIndex();
    input.focus();
    input.select();
  }

  function close(returnFocus) {
    show(false);
    active = -1;
    input.removeAttribute("aria-activedescendant");
    var wasOpen = isOpenNarrow();
    root.classList.remove("is-open");
    toggle.setAttribute("aria-expanded", "false");
    if (returnFocus) {
      if (wasOpen && getComputedStyle(toggle).display !== "none") toggle.focus();
      else input.blur();
    }
  }

  function go(i) {
    var r = results[i];
    if (!r) return;
    var href = hrefOf(r.s);
    close(false);
    input.blur();
    window.location.href = href;
  }

  /* ---------- Events ---------- */

  toggle.addEventListener("click", function () {
    if (isOpenNarrow()) close(true); else open();
  });
  closeBtn.addEventListener("click", function () {
    input.value = "";
    render();
    close(true);
  });

  input.addEventListener("focus", function () {
    loadIndex();
    if (input.value.trim()) render();
  });
  input.addEventListener("input", function () {
    clearTimeout(timer);
    timer = setTimeout(render, 60);
  });
  input.addEventListener("keydown", function (e) {
    if (e.key === "ArrowDown" || e.key === "Down") {
      e.preventDefault();
      if (list.hidden && input.value.trim()) render();
      setActive(active + 1);
    } else if (e.key === "ArrowUp" || e.key === "Up") {
      e.preventDefault();
      setActive(active < 0 ? -1 : active - 1);
    } else if (e.key === "Enter") {
      clearTimeout(timer);
      if (input.value.trim() && (!results.length || list.hidden)) render();
      if (results.length) { e.preventDefault(); go(active >= 0 ? active : 0); }
    } else if (e.key === "Escape" || e.key === "Esc") {
      e.preventDefault();
      if (!list.hidden && !isOpenNarrow()) { close(false); }
      else close(true);
    }
  });

  list.addEventListener("mousedown", function (e) {
    // Keep focus in the box while a result is clicked.
    if (e.target.closest && e.target.closest("a")) e.preventDefault();
  });
  list.addEventListener("click", function (e) {
    var a = e.target.closest && e.target.closest("a");
    if (!a || e.ctrlKey || e.metaKey || e.shiftKey || e.button !== 0) return;
    close(false);
  });
  list.addEventListener("mousemove", function (e) {
    var li = e.target.closest && e.target.closest('[role="option"]');
    if (!li) return;
    var i = parseInt(li.id.replace("docsearch-opt-", ""), 10);
    if (i !== active) setActive(i);
  });

  document.addEventListener("click", function (e) {
    if (!root.contains(e.target)) {
      if (!list.hidden) show(false);
      if (isOpenNarrow()) close(false);
    }
  });

  document.addEventListener("keydown", function (e) {
    var k = e.key;
    var isK = (k === "k" || k === "K") && (e.ctrlKey || e.metaKey) && !e.altKey && !e.shiftKey;
    var isSlash = k === "/" && !e.ctrlKey && !e.metaKey && !e.altKey;
    if (!isK && !isSlash) return;
    if (isSlash) {
      var t = e.target;
      var tag = t && t.tagName;
      if (tag === "INPUT" || tag === "TEXTAREA" || tag === "SELECT" || (t && t.isContentEditable)) return;
    } else if (document.activeElement === input) {
      e.preventDefault();
      input.select();
      return;
    }
    e.preventDefault();
    open();
  });
})();
