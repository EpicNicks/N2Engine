#!/usr/bin/env node
// Builds docs/assets/search-index.js, the index the search bar (assets/search.js) reads.
//
//   node docs/tools/build-search-index.mjs           write the index
//   node docs/tools/build-search-index.mjs --check   exit 1 if the committed index is stale
//
// Plain Node (16+), no npm packages. Reads every docs/*.html page except _template.html, takes the text
// inside <main> (without the "On this page" box and the page footer) and splits it into one record per
// h2/h3 section that has an id. Text before the first such heading belongs to the page itself (no
// anchor). A heading without an id stays inside the section before it, so every record links to an
// anchor that exists. Line endings are normalised, so the output is the same on Windows and Linux.
//
// The index is a script (it sets window.N2DocsSearchIndex), not JSON, so the search also works when the
// pages are opened straight from disk (file://), where fetch() is blocked.

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const docsDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(docsDir, "assets", "search-index.js");

const ENTITIES = {
  amp: "&", lt: "<", gt: ">", quot: "\"", apos: "'", nbsp: " ", mdash: "—", ndash: "–",
  middot: "·", minus: "−", times: "×", rarr: "→", larr: "←", hellip: "…",
  rsquo: "’", lsquo: "‘", ldquo: "“", rdquo: "”", copy: "©", deg: "°",
  ge: "≥", le: "≤", plusmn: "±", radic: "√", alpha: "α", nu: "ν", pi: "π"
};

function decode(s) {
  return s.replace(/&(#x[0-9a-fA-F]+|#\d+|[a-zA-Z]+);/g, (m, e) => {
    if (e[0] === "#") {
      const cp = e[1] === "x" || e[1] === "X" ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10);
      return Number.isFinite(cp) ? String.fromCodePoint(cp) : m;
    }
    return Object.prototype.hasOwnProperty.call(ENTITIES, e) ? ENTITIES[e] : m;
  });
}

// Block-level tags become a space so words on either side do not run together; inline tags vanish.
const BLOCK = /<\/?(?:p|div|li|ul|ol|pre|table|thead|tbody|tr|td|th|br|hr|h[1-6]|blockquote|dl|dt|dd|section|figure|figcaption|summary|details)\b[^>]*>/gi;

function toText(html) {
  return decode(html.replace(BLOCK, " ").replace(/<[^>]*>/g, ""))
    .replace(/[\s ]+/g, " ")
    .trim();
}

// A heading's PR badges (<span class="badge">PR #28</span>) stay out of its label.
function headingText(html) {
  return toText(html.replace(/<span class="badge">[\s\S]*?<\/span>/g, ""));
}

function indexPage(file) {
  const html = readFileSync(join(docsDir, file), "utf8").replace(/\r\n?/g, "\n");
  const titleMatch = /<title>([\s\S]*?)<\/title>/i.exec(html);
  const h1Match = /<h1\b[^>]*>([\s\S]*?)<\/h1>/i.exec(html);
  const title = headingText(h1Match ? h1Match[1] : titleMatch ? titleMatch[1].replace(/\s*·\s*N2Engine docs\s*$/, "") : file);

  const mainMatch = /<main\b[^>]*>([\s\S]*)<\/main>/i.exec(html);
  if (!mainMatch) throw new Error(`${file}: no <main> element`);
  let body = mainMatch[1]
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<(script|style)\b[\s\S]*?<\/\1>/gi, "")
    .replace(/<div class="toc">[\s\S]*?<\/div>/g, "")
    .replace(/<div class="page-footer">[\s\S]*?<\/div>/g, "")
    .replace(/<h1\b[^>]*>[\s\S]*?<\/h1>/i, "");

  const sections = [];
  let current = { h: title, a: "", parts: [] };
  const headingRe = /<h([23])\b([^>]*)>([\s\S]*?)<\/h\1>/gi;
  let last = 0;
  let m;
  while ((m = headingRe.exec(body)) !== null) {
    current.parts.push(body.slice(last, m.index));
    last = headingRe.lastIndex;
    const idMatch = /\bid="([^"]+)"/.exec(m[2]);
    if (idMatch) {
      sections.push(current);
      current = { h: headingText(m[3]), a: idMatch[1], parts: [] };
    } else {
      current.parts.push(" " + m[3] + " ");
    }
  }
  current.parts.push(body.slice(last));
  sections.push(current);

  return {
    title,
    sections: sections
      .map((s) => ({ h: s.h, a: s.a, x: toText(s.parts.join(" ")) }))
      .filter((s) => s.a !== "" || s.x !== "")
  };
}

function build() {
  const files = readdirSync(docsDir)
    .filter((f) => f.endsWith(".html") && !f.startsWith("_"))
    .sort();
  const pages = [];
  const sections = [];
  files.forEach((file, p) => {
    const page = indexPage(file);
    pages.push({ u: file, t: page.title });
    for (const s of page.sections) sections.push({ p, h: s.h, a: s.a, x: s.x });
  });
  // One record per line keeps diffs of the committed file readable.
  const lines = [
    "// Generated by docs/tools/build-search-index.mjs from docs/*.html. Do not edit by hand:",
    "// run `node docs/tools/build-search-index.mjs` after changing a page.",
    "window.N2DocsSearchIndex = {",
    "\"pages\": [",
    pages.map((p) => JSON.stringify(p)).join(",\n"),
    "],",
    "\"sections\": [",
    sections.map((s) => JSON.stringify(s)).join(",\n"),
    "]",
    "};",
    ""
  ];
  return { text: lines.join("\n"), pages: pages.length, sections: sections.length };
}

const result = build();
if (process.argv.includes("--check")) {
  let committed = "";
  try {
    committed = readFileSync(outFile, "utf8").replace(/\r\n?/g, "\n");
  } catch {
    committed = "";
  }
  if (committed !== result.text) {
    console.error("docs/assets/search-index.js is out of date: run `node docs/tools/build-search-index.mjs` and commit the result.");
    process.exit(1);
  }
  console.log(`search index is current (${result.pages} pages, ${result.sections} sections)`);
} else {
  writeFileSync(outFile, result.text);
  console.log(`wrote ${outFile} (${result.pages} pages, ${result.sections} sections, ${result.text.length} bytes)`);
}
